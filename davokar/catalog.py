def money_text(ortegs):
    t, rest = divmod(ortegs, 100)
    s, o = divmod(rest, 10)
    parts = []
    if t:
        parts.append(f"{t} thaler")
    if s:
        parts.append(f"{s} shilling" + ("s" if s > 1 else ""))
    if o or not parts:
        parts.append(f"{o} orteg" + ("s" if o != 1 else ""))
    return ", ".join(parts)
